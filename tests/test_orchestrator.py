@dataclass
class FakeReadonlyContext:
    """Lightweight stand-in for `google.adk.agents.readonly_context.ReadonlyContext`."""

    state: dict[str, Any] = field(default_factory=dict)
    user_text: str = ""

    @property
    def user_content(self) -> types.Content:
        return types.Content(role="user", parts=[types.Part.from_text(text=self.user_text)])


def test_intake_blocks_hallucinated_name_or_topic() -> None:
    """If the user only said 'hello', `apply_start_interview_to_state` stays in `intake` and rejects invented names."""
    state: dict[str, Any] = {"phase": str(Phase.INTAKE)}
    res = apply_start_interview_to_state(
        state,
        user_name="Participant 123",
        topic="AI in the workplace",
        questions=["Q1?", "Q2?", "Q3?"],
        user_history="hello",
    )
    assert res["status"] == "wait_for_user"
    assert state["phase"] == str(Phase.INTAKE)


def test_two_queues_main_then_followup_then_per_user_json_save(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Drains `question_queue` via `.pop(0)`, pushes to `followup_queue`, drains `followup_queue`, and saves `data/<user_id>.json`."""
    monkeypatch.setenv("DATA_DIR", str(tmp_path))
    state: dict[str, Any] = {"phase": str(Phase.INTAKE)}

    # 1. `start_interview` populates `question_queue` with 3 questions, pops Q1, and writes `data/victor.json`.
    started = apply_start_interview_to_state(
        state,
        user_name="Victor",
        topic="AI in the workplace",
        questions=[
            "How does AI fit into your daily workflow?",
            "How do you verify AI-generated outputs?",
            "Which skills have become more important because of AI?",
        ],
        user_history="Hi, I am Victor and I want to talk about AI in the workplace",
    )
    assert started["status"] == "ready"
    assert state["phase"] == str(Phase.MAIN_QUEUE)
    assert state["user_id"] == "victor"
    assert state["current_question"] == "How does AI fit into your daily workflow?"
    assert len(state["question_queue"]) == 2
    assert state["followup_queue"] == []
    assert (tmp_path / "victor.json").exists()

    # 2. User answers Q1 -> `advance_queues_on_user_answer` pops Q2 from `question_queue`.
    phase = advance_queues_on_user_answer(
        state,
        "I use AI every morning to automate unit tests and summarize pull requests.",
    )
    assert phase == Phase.MAIN_QUEUE
    assert state["current_question"] == "How do you verify AI-generated outputs?"
    assert len(state["question_queue"]) == 1

    # Agent decides A1 deserves a follow-up and pushes it onto `followup_queue`.
    pushed = apply_push_followup_to_state(
        state,
        follow_up_question="How do you handle flaky or hallucinated unit tests generated by AI?",
        referenced_answer="using AI to automate unit tests",
    )
    assert pushed["status"] == "pushed_to_followup_queue"
    assert len(state["followup_queue"]) == 1

    # 3. User skips Q2 -> `advance_queues_on_user_answer` records `[skipped]` and pops Q3.
    phase = advance_queues_on_user_answer(state, "skip")
    assert phase == Phase.MAIN_QUEUE
    assert state["transcript"][1]["answer"] == SKIPPED_ANSWER
    assert state["current_question"] == "Which skills have become more important because of AI?"
    assert state["question_queue"] == []

    # 4. User answers Q3 -> `question_queue` is now empty, so it pops from `followup_queue` (`FOLLOWUP_QUEUE`).
    phase = advance_queues_on_user_answer(
        state,
        "Clear problem decomposition and reviewing edge cases.",
    )
    assert phase == Phase.FOLLOWUP_QUEUE
    assert (
        state["current_question"]
        == "How do you handle flaky or hallucinated unit tests generated by AI?"
    )
    assert state["current_followup_context"] == "using AI to automate unit tests"
    assert state["followup_queue"] == []

    # Verify that in `FOLLOWUP_QUEUE`, no tools are exposed so it can never loop.
    assert ALLOWED_TOOLS_BY_PHASE[Phase.FOLLOWUP_QUEUE] == set()
    blocked = apply_push_followup_to_state(
        state,
        follow_up_question="Another follow-up?",
        referenced_answer="edge cases",
    )
    assert blocked["status"] == "ignored"

    # 5. User answers the follow-up -> both queues are empty -> programmatically transitions to `DONE` and saves `victor.json`!
    phase = advance_queues_on_user_answer(
        state,
        "We run mutation testing and require a human review on every assertion.",
    )
    assert phase == Phase.DONE
    assert state["current_question"] is None
    assert len(state["transcript"]) == 4

    saved_file = tmp_path / "victor.json"
    assert saved_file.exists()
    record = json.loads(saved_file.read_text(encoding="utf-8"))
    assert record["user_id"] == "victor"
    assert record["status"] == "pending_analysis"
    assert "saved_to_disk" not in record
    assert "saved_path" not in record
    assert "summary" not in record

    # 6. Starting an interview for a second user creates a second JSON file (`alex.json`).
    state2: dict[str, Any] = {"phase": str(Phase.INTAKE)}
    apply_start_interview_to_state(
        state2,
        user_name="Alex",
        topic="Remote work",
        questions=["Q1?", "Q2?", "Q3?"],
        user_history="I am Alex and I want to discuss Remote work",
    )
    assert (tmp_path / "alex.json").exists()
    assert (tmp_path / "victor.json").exists()

    # 7. `reset_interview_state` resets back to `intake`.
    restarted = reset_interview_state(state)
    assert restarted["status"] == "restarted"
    assert state["phase"] == str(Phase.INTAKE)
    assert state["transcript"] == []


def test_mcp_toolset_http_and_phase_prompts(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Verifies `LlmAgent` uses `McpToolset` over HTTP and `PHASE_PROMPTS` formats all 4 phases."""
    monkeypatch.setenv("DATA_DIR", str(tmp_path))
    agent = build_interview_harness(num_questions=2, mcp_url="http://mcp:8001/mcp")
    assert agent.name == "interview_orchestrator"
    assert len(agent.tools) == 1
    assert isinstance(agent.tools[0], McpToolset)

    ctx = FakeReadonlyContext(
        state={"phase": str(Phase.INTAKE), "num_questions_override": 2},
        user_text="I'm Victor, topic: AI in the workplace",
    )
    assert "Current State: `intake`" in build_harness_instruction(ctx)  # type: ignore[arg-type]

    apply_start_interview_to_state(
        ctx.state,
        user_name="Victor",
        topic="AI in the workplace",
        questions=["Q1?", "Q2?", "Q3?"],
        user_history="I'm Victor, topic: AI in the workplace",
    )
    assert ctx.state["current_question"] == "Q1?"
    assert ctx.state["question_queue"] == ["Q2?"]
    assert "Current State: `main_queue`" in build_harness_instruction(ctx)  # type: ignore[arg-type]

    # Short answer ("ok") on Q1 auto-pushes a clarification follow-up onto `followup_queue` and pops Q2.
    advance_queues_on_user_answer(ctx.state, "ok")
    assert ctx.state["current_question"] == "Q2?"
    assert len(ctx.state["followup_queue"]) == 1

    # Answering Q2 drains `question_queue` and transitions to `followup_queue`.
    advance_queues_on_user_answer(ctx.state, "I verify everything manually before merging.")
    assert ctx.state["phase"] == str(Phase.FOLLOWUP_QUEUE)
    assert "Current State: `followup_queue`" in build_harness_instruction(ctx)  # type: ignore[arg-type]

    # Answering the follow-up drains `followup_queue`, transitions to `done`, and saves `victor.json`.
    advance_queues_on_user_answer(ctx.state, "Specifically I use it for summarizing daily emails.")
    assert ctx.state["phase"] == str(Phase.DONE)
    assert (tmp_path / "victor.json").exists()
    done_prompt = build_harness_instruction(ctx)  # type: ignore[arg-type]
    assert "Current State: `done`" in done_prompt
    assert "do NOT generate a summary in chat" in done_prompt
