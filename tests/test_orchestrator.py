"""Unit and state-machine tests for the Two-Queue `LlmAgent` interview harness (`orchestrator.py`)."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from google.genai import types

from interviewer_app.orchestrator import (
    ALLOWED_TOOLS_BY_PHASE,
    Phase,
    advance_queues_on_user_answer,
    build_harness_instruction,
    build_interview_harness,
    end_interview,
    push_followup,
    start_interview,
)
from interviewer_app.schemas import SKIPPED_ANSWER


@dataclass
class FakeToolContext:
    """Lightweight stand-in for `google.adk.tools.ToolContext` used in unit tests."""

    state: dict[str, Any] = field(default_factory=dict)
    user_text: str = ""

    @property
    def user_content(self) -> types.Content:
        return types.Content(role="user", parts=[types.Part.from_text(text=self.user_text)])

    @property
    def session(self) -> Any:
        return None


def test_intake_blocks_hallucinated_name_or_topic() -> None:
    """If the user only said 'hello', `start_interview` stays in `intake` and rejects invented names."""
    ctx = FakeToolContext(state={"phase": str(Phase.INTAKE)}, user_text="hello")
    res = start_interview(
        user_name="Participant 123",
        topic="AI in the workplace",
        questions=["Q1?", "Q2?", "Q3?"],
        tool_context=ctx,  # type: ignore[arg-type]
    )
    assert res["status"] == "wait_for_user"
    assert ctx.state["phase"] == str(Phase.INTAKE)


def test_two_queues_main_then_followup_then_done() -> None:
    """Drains `question_queue` via `.pop(0)`, pushes to `followup_queue`, drains `followup_queue`, and stops."""
    ctx = FakeToolContext(
        state={"phase": str(Phase.INTAKE)},
        user_text="Hi, I am Victor and I want to talk about AI in the workplace",
    )

    # 1. `start_interview` populates `question_queue` with 3 questions and immediately pops Q1.
    started = start_interview(
        user_name="Victor",
        topic="AI in the workplace",
        questions=[
            "How does AI fit into your daily workflow?",
            "How do you verify AI-generated outputs?",
            "Which skills have become more important because of AI?",
        ],
        tool_context=ctx,  # type: ignore[arg-type]
    )
    assert started["status"] == "ready"
    assert ctx.state["phase"] == str(Phase.MAIN_QUEUE)
    assert ctx.state["current_question"] == "How does AI fit into your daily workflow?"
    assert len(ctx.state["question_queue"]) == 2
    assert ctx.state["followup_queue"] == []

    # 2. User answers Q1 -> `advance_queues_on_user_answer` pops Q2 from `question_queue`.
    phase = advance_queues_on_user_answer(
        ctx.state,
        "I use AI every morning to automate unit tests and summarize pull requests.",
    )
    assert phase == Phase.MAIN_QUEUE
    assert ctx.state["current_question"] == "How do you verify AI-generated outputs?"
    assert len(ctx.state["question_queue"]) == 1

    # Agent decides A1 deserves a follow-up and pushes it onto `followup_queue`.
    pushed = push_followup(
        follow_up_question="How do you handle flaky or hallucinated unit tests generated by AI?",
        referenced_answer="using AI to automate unit tests",
        tool_context=ctx,  # type: ignore[arg-type]
    )
    assert pushed["status"] == "pushed_to_followup_queue"
    assert len(ctx.state["followup_queue"]) == 1

    # 3. User skips Q2 -> `advance_queues_on_user_answer` records `[skipped]` and pops Q3.
    phase = advance_queues_on_user_answer(ctx.state, "skip")
    assert phase == Phase.MAIN_QUEUE
    assert ctx.state["transcript"][1]["answer"] == SKIPPED_ANSWER
    assert ctx.state["current_question"] == "Which skills have become more important because of AI?"
    assert ctx.state["question_queue"] == []

    # 4. User answers Q3 -> `question_queue` is now empty, so it pops from `followup_queue` (`FOLLOWUP_QUEUE`).
    phase = advance_queues_on_user_answer(
        ctx.state,
        "Clear problem decomposition and reviewing edge cases.",
    )
    assert phase == Phase.FOLLOWUP_QUEUE
    assert (
        ctx.state["current_question"]
        == "How do you handle flaky or hallucinated unit tests generated by AI?"
    )
    assert ctx.state["current_followup_context"] == "using AI to automate unit tests"
    assert ctx.state["followup_queue"] == []

    # Verify that in `FOLLOWUP_QUEUE`, `push_followup` is blocked so it can never loop.
    assert "push_followup" not in ALLOWED_TOOLS_BY_PHASE[Phase.FOLLOWUP_QUEUE]
    blocked = push_followup(
        follow_up_question="Another follow-up?",
        referenced_answer="edge cases",
        tool_context=ctx,  # type: ignore[arg-type]
    )
    assert blocked["status"] == "ignored"

    # 5. User answers the follow-up -> both queues are empty -> transitions to `DONE`.
    phase = advance_queues_on_user_answer(
        ctx.state,
        "We run mutation testing and require a human review on every assertion.",
    )
    assert phase == Phase.DONE
    assert ctx.state["current_question"] is None
    assert len(ctx.state["transcript"]) == 4

    # 6. `end_interview(action='restart')` resets back to `intake`.
    restarted = end_interview(action="restart", tool_context=ctx)  # type: ignore[arg-type]
    assert restarted["status"] == "restarted"
    assert ctx.state["phase"] == str(Phase.INTAKE)
    assert ctx.state["transcript"] == []


def test_num_questions_override_and_phase_prompts() -> None:
    """`num_questions_override=2` caps `question_queue` at 2 questions and formats all 4 `PHASE_PROMPTS`."""
    agent = build_interview_harness(num_questions=2)
    assert agent.name == "interview_orchestrator"
    assert ALLOWED_TOOLS_BY_PHASE[Phase.INTAKE] == {"start_interview"}
    assert ALLOWED_TOOLS_BY_PHASE[Phase.MAIN_QUEUE] == {"push_followup", "end_interview"}
    assert ALLOWED_TOOLS_BY_PHASE[Phase.FOLLOWUP_QUEUE] == {"end_interview"}
    assert ALLOWED_TOOLS_BY_PHASE[Phase.DONE] == {"end_interview"}

    ctx = FakeToolContext(
        state={"phase": str(Phase.INTAKE), "num_questions_override": 2},
        user_text="I'm Victor, topic: AI in the workplace",
    )
    assert "Current State: `intake`" in build_harness_instruction(ctx)  # type: ignore[arg-type]

    start_interview(
        user_name="Victor",
        topic="AI in the workplace",
        questions=["Q1?", "Q2?", "Q3?"],
        tool_context=ctx,  # type: ignore[arg-type]
    )
    assert ctx.state["current_question"] == "Q1?"
    assert ctx.state["question_queue"] == ["Q2?"]
    assert "Phase:** `main_queue`" in build_harness_instruction(ctx)  # type: ignore[arg-type]

    # Short answer ("ok") on Q1 auto-pushes a clarification follow-up onto `followup_queue` and pops Q2.
    advance_queues_on_user_answer(ctx.state, "ok")
    assert ctx.state["current_question"] == "Q2?"
    assert len(ctx.state["followup_queue"]) == 1

    # Answering Q2 drains `question_queue` and transitions to `followup_queue`.
    advance_queues_on_user_answer(ctx.state, "I verify everything manually before merging.")
    assert ctx.state["phase"] == str(Phase.FOLLOWUP_QUEUE)
    assert "Phase:** `followup_queue`" in build_harness_instruction(ctx)  # type: ignore[arg-type]

    # Answering the follow-up drains `followup_queue` and transitions to `done`.
    advance_queues_on_user_answer(ctx.state, "Specifically I use it for summarizing daily emails.")
    assert ctx.state["phase"] == str(Phase.DONE)
    assert "Current State: `done`" in build_harness_instruction(ctx)  # type: ignore[arg-type]
